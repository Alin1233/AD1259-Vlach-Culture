<#
.SYNOPSIS
    Generates the vlach_generated_*.xml data files of the "AD1259 - Vlach Culture" submod.

.DESCRIPTION
    Reads the design in tools/vlach.config.psd1 and Bulgaria's data from an installed
    Anno Domini 1259, and writes four files into Module/ModuleData:

      vlach_generated_culture.xml     SPCultures      the playable Vlach culture
      vlach_generated_troops.xml      NPCCharacters   the Vlach troop tree
      vlach_generated_characters.xml  NPCCharacters   notable / headman / lord / child-education templates
      vlach_generated_equipment.xml   EquipmentRosters culture-tagged and culture-keyed rosters

    The output is deterministic: running it twice on the same AD1259 version produces
    identical files, so the generated files can be committed and reviewed.

    Run it again only when the design (config) changes or AD1259 is updated.

.PARAMETER GameDir
    Bannerlord installation folder containing Modules\AD1259.

.PARAMETER OutDir
    Destination folder (defaults to the repository's Module\ModuleData).

.PARAMETER Force
    Generate even if the installed AD1259 version differs from Ad1259Version in the config.

.EXAMPLE
    powershell -ExecutionPolicy Bypass -File tools\Generate-ModuleData.ps1
#>
[CmdletBinding()]
param(
    [string]$GameDir = 'C:\Program Files (x86)\Steam\steamapps\common\Mount & Blade II Bannerlord',
    [string]$OutDir,
    [string]$ConfigPath,
    [switch]$Force
)

Set-StrictMode -Version 2
$ErrorActionPreference = 'Stop'

# ($PSScriptRoot is not available in parameter defaults on Windows PowerShell 5.1.)
$here = Split-Path -Parent $MyInvocation.MyCommand.Path
if (-not $OutDir) { $OutDir = Join-Path $here '..\Module\ModuleData' }
if (-not $ConfigPath) { $ConfigPath = Join-Path $here 'vlach.config.psd1' }

. (Join-Path $here 'Common.ps1')

$cfg = Read-VlachConfig -Path $ConfigPath
$ad1259 = Join-Path $GameDir 'Modules\AD1259'
$data = Join-Path $ad1259 'ModuleData'
$OutDir = [IO.Path]::GetFullPath($OutDir)
$templateId = $cfg.TemplateCulture
$cultureId = $cfg.Culture.Id

# --- 0. Check the AD1259 version --------------------------------------------------
$installed = Get-ModuleVersion -SubModulePath (Join-Path $ad1259 'SubModule.xml')
if ($installed -ne $cfg.Ad1259Version) {
    $msg = "Installed AD1259 is $installed but the config targets $($cfg.Ad1259Version)."
    if ($Force) { Write-Warning "$msg Continuing because -Force was given." } else { throw "$msg Use -Force to generate anyway." }
}
Write-Host "Generating from AD1259 $installed in $data"

function Convert-TemplateId([string]$Id) {
    # bulgaria -> vlach inside an id, e.g. player_char_creation_bulgaria_guard_m
    return $Id -replace $templateId, $cultureId
}

function New-Header([string]$what) {
    return " Generated by tools/Generate-ModuleData.ps1 from Anno Domini 1259 $installed. " +
           "Do not edit by hand: change tools/vlach.config.psd1 and run the generator again. $what "
}

# =================================================================================
# 1. Equipment rosters
# =================================================================================
$equipment = New-DataDocument -Root 'EquipmentRosters' -Comment (New-Header 'Copies of Bulgaria''s culture-tagged equipment rosters, retagged as Vlach.')
$rosters = New-Object 'System.Collections.Specialized.OrderedDictionary'
$duplicates = 0
foreach ($rel in $cfg.EquipmentSources) {
    $src = Read-XmlFile (Join-Path $data $rel)
    foreach ($node in $src.SelectNodes('/EquipmentRosters/EquipmentRoster')) {
        $id = $node.GetAttribute('id')
        if ($id -notmatch $templateId -or $id -match $cfg.EquipmentIdExcludePattern) { continue }
        $clone = $equipment.ImportNode($node, $true)
        $newId = Convert-TemplateId $id
        $clone.SetAttribute('id', $newId)
        if ($clone.HasAttribute('culture')) { $clone.SetAttribute('culture', "Culture.$cultureId") }
        # Same id in two AD1259 files: the later file wins in game, so it wins here too.
        if ($rosters.Contains($newId)) { $rosters.Remove($newId); $duplicates++ }
        $rosters.Add($newId, @{ Node = $clone; From = "$rel : $id" })
    }
}
foreach ($key in $rosters.Keys) {
    $entry = $rosters[$key]
    [void]$equipment.DocumentElement.AppendChild($equipment.CreateComment(" from $($entry.From) "))
    [void]$equipment.DocumentElement.AppendChild($entry.Node)
}
Save-XmlFile $equipment (Join-Path $OutDir 'vlach_generated_equipment.xml')
Write-Host ("  equipment rosters : {0} ({1} duplicate ids resolved)" -f $rosters.Count, $duplicates)

# =================================================================================
# 2. NPC templates (notables, headmen, lord templates, child education)
# =================================================================================
$characters = New-DataDocument -Root 'NPCCharacters' -Comment (New-Header 'Copies of Bulgaria''s notable, headman, lord and child-education templates, retagged as Vlach.')
$characterIds = New-Object 'System.Collections.Generic.HashSet[string]'

# A few AD1259 templates reference equipment rosters that do not exist (for example
# spc_notable_bulgaria_3, or spc_notable_bulgaria_3c where the roster is spelled
# "spc_notabble_bulgaria_3c"). The clones drop such dangling references; their other
# equipment sets are kept.
$knownRosters = New-Object 'System.Collections.Generic.HashSet[string]'
$readerSettings = New-Object System.Xml.XmlReaderSettings
$readerSettings.DtdProcessing = [System.Xml.DtdProcessing]::Ignore
foreach ($dir in @($data) + @('Native', 'SandBoxCore', 'SandBox' | ForEach-Object { Join-Path $GameDir "Modules\$_\ModuleData" })) {
    if (-not (Test-Path $dir)) { continue }
    foreach ($f in Get-ChildItem $dir -Recurse -Filter '*.xml') {
        $r = [System.Xml.XmlReader]::Create($f.FullName, $readerSettings)
        try {
            while ($r.Read()) {
                if ($r.NodeType -eq [System.Xml.XmlNodeType]::Element -and $r.LocalName -eq 'EquipmentRoster') {
                    $rid = $r.GetAttribute('id'); if ($rid) { [void]$knownRosters.Add($rid) }
                }
            }
        } catch { } finally { $r.Close() }
    }
}
$dropped = 0
foreach ($rel in $cfg.CharacterSources) {
    $src = Read-XmlFile (Join-Path $data $rel)
    foreach ($node in $src.SelectNodes('/NPCCharacters/NPCCharacter')) {
        $id = $node.GetAttribute('id')
        if ($id -notmatch $cfg.CharacterIdPattern -or $id -notmatch $templateId) { continue }
        $clone = $characters.ImportNode($node, $true)
        $newId = Convert-TemplateId $id
        $clone.SetAttribute('id', $newId)
        $clone.SetAttribute('culture', "Culture.$cultureId")
        if ($clone.HasAttribute('name')) {
            $clone.SetAttribute('name', (Convert-LocalizedText $clone.GetAttribute('name') { param($t) $t -replace "(?i)$templateId", $cultureId }))
        }
        foreach ($set in @($clone.SelectNodes('.//EquipmentSet[@id]'))) {
            $rid = $set.GetAttribute('id')
            if (-not $knownRosters.Contains($rid)) {
                $note = $characters.CreateComment(" dropped EquipmentSet '$rid': no such roster in AD1259 ")
                [void]$set.ParentNode.ReplaceChild($note, $set)
                $dropped++
            }
        }
        [void]$characters.DocumentElement.AppendChild($characters.CreateComment(" from $rel : $id "))
        [void]$characters.DocumentElement.AppendChild($clone)
        [void]$characterIds.Add($newId)
    }
}
Save-XmlFile $characters (Join-Path $OutDir 'vlach_generated_characters.xml')
Write-Host ("  NPC templates     : {0} ({1} dangling equipment references dropped)" -f $characterIds.Count, $dropped)

# =================================================================================
# 3. Troop tree
# =================================================================================
$troopIndex = @{}
foreach ($file in Get-ChildItem (Join-Path $data 'trooptrees') -Filter '*.xml') {
    foreach ($node in (Read-XmlFile $file.FullName).SelectNodes('/NPCCharacters/NPCCharacter')) {
        $troopIndex[$node.GetAttribute('id')] = $node
    }
}
$troops = New-DataDocument -Root 'NPCCharacters' -Comment (New-Header 'The Vlach troop tree. Skills and equipment are taken from the AD1259 troops named in each comment.')
$copiedAttributes = @('id', 'name', 'culture', 'level', 'default_group', 'is_basic_troop', 'occupation')
foreach ($t in $cfg.Troops) {
    $src = $troopIndex[$t.Source]
    if ($null -eq $src) { throw "Troop $($t.Id): source troop '$($t.Source)' not found in AD1259 trooptrees." }

    $n = $troops.CreateElement('NPCCharacter')
    $n.SetAttribute('id', $t.Id)
    $optSkills = Get-Opt $t 'Skills'
    $optUpgrades = Get-Opt $t 'Upgrades'
    $n.SetAttribute('default_group', (Select-First (Get-Opt $t 'Group') $src.GetAttribute('default_group')))
    $n.SetAttribute('level', (Select-First (Get-Opt $t 'Level') $src.GetAttribute('level')))
    $n.SetAttribute('name', "{=ad1259vlach_troop_$($t.Id -replace '^vlach_', '')}$($t.Name)")
    $n.SetAttribute('occupation', 'Soldier')
    $n.SetAttribute('culture', "Culture.$cultureId")
    if (Get-Opt $t 'Basic') { $n.SetAttribute('is_basic_troop', 'true') }
    foreach ($a in $src.Attributes) {
        if ($copiedAttributes -notcontains $a.Name) { $n.SetAttribute($a.Name, $a.Value) }
    }

    $face = $troops.CreateElement('face')
    $fk = $troops.CreateElement('face_key_template'); $fk.SetAttribute('value', $cfg.Face)
    [void]$face.AppendChild($fk); [void]$n.AppendChild($face)

    $skills = $troops.CreateElement('skills')
    foreach ($s in $src.SelectNodes('skills/skill')) {
        $sk = $troops.CreateElement('skill'); $sid = $s.GetAttribute('id')
        $value = $s.GetAttribute('value')
        if ($optSkills -and $optSkills.ContainsKey($sid)) { $value = $optSkills[$sid] }
        $sk.SetAttribute('id', $sid); $sk.SetAttribute('value', $value)
        [void]$skills.AppendChild($sk)
    }
    [void]$n.AppendChild($skills)

    if ($optUpgrades) {
        $ut = $troops.CreateElement('upgrade_targets')
        foreach ($u in $optUpgrades) {
            $x = $troops.CreateElement('upgrade_target'); $x.SetAttribute('id', "NPCCharacter.$u"); [void]$ut.AppendChild($x)
        }
        [void]$n.AppendChild($ut)
    }

    $eq = $troops.CreateElement('Equipments')
    $battle = Select-First (Get-Opt $t 'Battle') ($src.SelectSingleNode('Equipments/EquipmentSet[not(@equipmentType)]').GetAttribute('id'))
    $civil = Select-First (Get-Opt $t 'Civilian') ($src.SelectSingleNode("Equipments/EquipmentSet[@equipmentType='Civilian']").GetAttribute('id'))
    $b = $troops.CreateElement('EquipmentSet'); $b.SetAttribute('id', $battle); [void]$eq.AppendChild($b)
    $c = $troops.CreateElement('EquipmentSet'); $c.SetAttribute('id', $civil); $c.SetAttribute('equipmentType', 'Civilian'); [void]$eq.AppendChild($c)
    [void]$n.AppendChild($eq)

    $skillNote = if ($optSkills) { "custom skills (base $($t.Source))" } else { "skills from $($t.Source)" }
    [void]$troops.DocumentElement.AppendChild($troops.CreateComment(" $($t.Name): $skillNote, battle gear $battle "))
    [void]$troops.DocumentElement.AppendChild($n)
}
Save-XmlFile $troops (Join-Path $OutDir 'vlach_generated_troops.xml')
Write-Host ("  troops            : {0}" -f @($cfg.Troops).Count)

# =================================================================================
# 4. Culture
# =================================================================================
$cultureSrc = $null
foreach ($file in Get-ChildItem (Join-Path $data 'spcultures') -Filter '*.xml') {
    $hit = (Read-XmlFile $file.FullName).SelectSingleNode("/SPCultures/Culture[@id='$templateId']")
    if ($hit) { $cultureSrc = $hit; break }
}
if ($null -eq $cultureSrc) { throw "Template culture '$templateId' not found." }

$clanBanner = $null
foreach ($file in Get-ChildItem (Join-Path $data 'spclans') -Filter '*.xml') {
    $hit = (Read-XmlFile $file.FullName).SelectSingleNode("/Factions/Faction[@id='$($cfg.Culture.BannerFromClan)']")
    if ($hit) { $clanBanner = $hit.GetAttribute('banner_key'); break }
}
if (-not $clanBanner) { throw "Clan '$($cfg.Culture.BannerFromClan)' (banner source) not found." }

$culture = New-DataDocument -Root 'SPCultures' -Comment (New-Header "The playable Vlach culture. Attributes not set in the config are shared with '$templateId'.")
$cu = $culture.ImportNode($cultureSrc, $true)
$cu.SetAttribute('id', $cultureId)
$cu.SetAttribute('name', $cfg.Culture.Name)
$cu.SetAttribute('is_main_culture', 'true')
$cu.SetAttribute('color', $cfg.Culture.Color)
$cu.SetAttribute('color2', $cfg.Culture.Color2)
$cu.SetAttribute('faction_banner_key', $clanBanner)
$cu.SetAttribute('start_point_position_x', $cfg.Culture.StartX)
$cu.SetAttribute('start_point_position_y', $cfg.Culture.StartY)
foreach ($key in ($cfg.Culture.Attributes.Keys | Sort-Object)) {
    if (-not $cu.HasAttribute($key)) { throw "Culture attribute '$key' does not exist on the template culture (typo?)." }
    $cu.SetAttribute($key, $cfg.Culture.Attributes[$key])
}

function Set-NameList([System.Xml.XmlElement]$parent, [string]$element, [string[]]$names, [string]$prefix) {
    $list = $parent.SelectSingleNode($element)
    if ($null -eq $list) { throw "Template culture has no <$element>." }
    $list.RemoveAll()
    $i = 0
    foreach ($nm in $names) {
        $e = $parent.OwnerDocument.CreateElement('name')
        $e.SetAttribute('name', ('{{=ad1259vlach_{0}_{1:00}}}{2}' -f $prefix, $i, $nm))
        [void]$list.AppendChild($e); $i++
    }
}
Set-NameList $cu 'male_names' $cfg.Culture.MaleNames 'm'
Set-NameList $cu 'female_names' $cfg.Culture.FemaleNames 'f'
Set-NameList $cu 'clan_names' $cfg.Culture.ClanNames 'clan'

$feats = $cu.SelectSingleNode('cultural_feats'); $feats.RemoveAll()
foreach ($f in $cfg.Culture.Feats) { $e = $culture.CreateElement('feat'); $e.SetAttribute('id', $f); [void]$feats.AppendChild($e) }

# Template lists: point every Bulgarian template at its Vlach clone.
foreach ($listName in 'notable_templates', 'lord_templates', 'rebellion_hero_templates') {
    foreach ($tpl in $cu.SelectNodes("$listName/template")) {
        $old = $tpl.GetAttribute('name') -replace '^NPCCharacter\.', ''
        $new = Convert-TemplateId $old
        if (-not $characterIds.Contains($new)) { throw "$listName references '$old' but no clone '$new' was generated." }
        $tpl.SetAttribute('name', "NPCCharacter.$new")
    }
}
[void]$culture.DocumentElement.AppendChild($cu)
Save-XmlFile $culture (Join-Path $OutDir 'vlach_generated_culture.xml')
Write-Host ("  culture           : {0} ({1} male, {2} female, {3} clan names; feats: {4})" -f $cultureId,
    @($cfg.Culture.MaleNames).Count, @($cfg.Culture.FemaleNames).Count, @($cfg.Culture.ClanNames).Count, ($cfg.Culture.Feats -join ', '))
Write-Host "Done. Output: $OutDir"
